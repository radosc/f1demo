inline int pidType(int pid) { return (pid >> 24) & 0xF; }
inline int pidIndex(int pid) { return pid & 0xFFFFFF; }
inline int fidType(int fid) { return (fid >> 24) & 0xF; }
inline int fidIndex(int fid) { return fid & 0xFFF; }
inline int fidAnim(int fid) { return (fid >> 16) & 0xFF; }
inline int fidWeapon(int fid) { return (fid >> 12) & 0xF; }
inline int fidRot(int fid) { return (fid >> 28) & 0x7; }
inline int makeFid(int type, int index, int anim = 0, int weapon = 0, int rot = 0)
{
    return ((rot & 7) << 28) | ((type & 0xF) << 24) | ((anim & 0xFF) << 16) | ((weapon & 0xF) << 12) | (index & 0xFFF);
}
